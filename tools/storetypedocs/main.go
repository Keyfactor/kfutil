func createHeaders(st storeType) []string {
	headers := []string{
		"ContainerId",
		"ClientMachine",
		"StorePath",
		"CreateIfMissing",
	}
	for _, prop := range st.Properties {
		headers = append(headers, "Properties."+prop.Name)
	}
	headers = append(headers,
		"AgentId",
		"InventorySchedule.Immediate",
		"InventorySchedule.Interval.Minutes",
		"InventorySchedule.Daily.Time",
		"InventorySchedule.Weekly.Days",
		"InventorySchedule.Weekly.Time",
	)
	if st.PasswordOptions.StoreRequired {
		headers = append(headers, "Password")
	}
	return headers
}

func updateHeaders(st storeType) []string {
	headers := append([]string{"Id"}, createHeaders(st)...)
	return headers
}

func secretProperties(st storeType) []storeTypeProperty {
	var props []storeTypeProperty
	for _, prop := range st.Properties {
		if isSecretProperty(prop) {
			props = append(props, prop)
		}
	}
	return props
}

func isSecretProperty(prop storeTypeProperty) bool {
	return strings.EqualFold(prop.Type, "Secret") || prop.IsPAMEligible || prop.IsPamEligable
}

func secretPropertySummary(prop storeTypeProperty) string {
	if !isSecretProperty(prop) {
		return "No"
	}
	if prop.IsPAMEligible || prop.IsPamEligable {
		return "Secret; PAM eligible"
	}
	return "Secret"
}

func storePasswordSummary(options passwordOptions) string {
	if options.StoreRequired {
		if options.StorePassword != nil && options.StorePassword.IsPAMEligible {
			return "Required; PAM eligible"
		}
		return "Required"
	}
	if options.StorePassword != nil && options.StorePassword.IsPAMEligible {
		return "Optional; PAM eligible"
	}
	return "Not required"
}

func secretColumnSummary(secretCount int) string {
	switch secretCount {
	case 0:
		return "None"
	case 1:
		return "1 secret property"
	default:
		return fmt.Sprintf("%d secret properties", secretCount)
	}
}

func supportedOperations(ops map[string]bool) string {
	if len(ops) == 0 {
		return "-"
	}
	var enabled []string
	for op, ok := range ops {
		if ok {
			enabled = append(enabled, op)
		}
	}
	sort.Strings(enabled)
	if len(enabled) == 0 {
		return "None"
	}
	return strings.Join(enabled, ", ")
}

func value(v any) string {
	if v == nil {
		return "-"
	}
	switch typed := v.(type) {
	case string:
		return blank(typed)
	case bool:
		return yesNo(typed)
	case float64:
		return fmt.Sprintf("%v", typed)
	default:
		data, err := json.Marshal(typed)
		if err != nil {
			return fmt.Sprintf("%v", typed)
		}
		return string(data)
	}
}

func blank(s string) string {
	if strings.TrimSpace(s) == "" {
		return "-"
	}
	return s
}

func yesNo(v bool) string {
	if v {
		return "Yes"
	}
	return "No"
}

func mdTable(s string) string {
	s = mdText(s)
	s = strings.ReplaceAll(s, "|", `\|`)
	return s
}

func mdText(s string) string {
	s = strings.TrimSpace(s)
	if s == "" {
		return "-"
	}
	s = html.EscapeString(s)
	s = strings.ReplaceAll(s, "\r\n", "\n")
	s = strings.ReplaceAll(s, "\r", "\n")
	s = strings.ReplaceAll(s, "\n", "<br>")
	return s
}

func shellName(value string) string {
	return slugify(value)
}

func shellQuote(value string) string {
	if regexp.MustCompile(`^[A-Za-z0-9._-]+$`).MatchString(value) {
		return value
	}
	return "'" + strings.ReplaceAll(value, "'", `'\''`) + "'"
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
